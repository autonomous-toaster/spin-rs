//! Lua code generator: compiles Promela IR into Lua scripts.
//!
//! The generated Lua is loaded by the mlua runtime and called by the
//! verification engine for model-specific transition enumeration.

use crate::parser::ast::*;

/// Generated Lua code components.
#[derive(Debug, Clone)]
pub struct GeneratedLua {
    /// The full Lua source as a string.
    pub source: String,
    /// Per-proctype transition enumerator names.
    pub proctype_fn_names: Vec<String>,
}

/// Compile a Promela model into Lua source code.
pub fn generate(model: &PromelaModel) -> GeneratedLua {
    let mut g = LuaGenerator::new();
    g.emit_header();
    g.emit_state_layout(model);
    g.emit_proctypes(model);
    g.emit_trailer();
    g.finish()
}

struct LuaGenerator {
    source: String,
    indent: usize,
    proctype_names: Vec<String>,
}

impl LuaGenerator {
    fn new() -> Self {
        Self {
            source: String::new(),
            indent: 0,
            proctype_names: Vec::new(),
        }
    }

    fn emit(&mut self, line: &str) {
        if !line.is_empty() {
            self.source.push_str(&"    ".repeat(self.indent));
            self.source.push_str(line);
        }
        self.source.push('\n');
    }

    fn emit_header(&mut self) {
        self.emit("-- Generated by spin-rs Lua code generator");
        self.emit("-- Runtime: mlua 5.4");
        self.emit("");
        self.emit("-- Channel operations (Rust FFI)");
        self.emit("local chan_send = _spin_chan_send");
        self.emit("local chan_recv = _spin_chan_recv");
        self.emit("local chan_len = _spin_chan_len");
        self.emit("local chan_full = _spin_chan_full");
        self.emit("local chan_empty = _spin_chan_empty");
        self.emit("local assert = _spin_assert");
        self.emit("local printf = _spin_printf");
        self.emit("local state_hash = _spin_state_hash");
        self.emit("");

        self.emit("-- State initialization");
        self.emit("-- Called once to create the initial state vector");
        self.emit("function _spin_init_state()");
        self.indent += 1;
    }

    fn emit_state_layout(&mut self, model: &PromelaModel) {
        // Collect all global variables
        let mut lines = Vec::new();
        for decl in &model.declarations {
            match decl {
                TopLevel::GlobalVar(v) => {
                    let default = default_value(&v.var_type);
                    lines.push(format!("    state.{} = {}", v.name, default));
                }
                TopLevel::Proctype(p) => {
                    // Proctype local variables will be per-process in state
                    for param in &p.parameters {
                        let default = default_value(&param.var_type);
                        lines.push(format!(
                            "    state.{}_p{}_{} = {}",
                            "", p.name, param.name, default
                        ));
                    }
                }
                _ => {}
            }
        }

        // Count processes for initialization
        let active_count: usize = model
            .declarations
            .iter()
            .filter(|d| matches!(d, TopLevel::Proctype(p) if p.active))
            .count();

        self.emit("    local state = {}");
        self.emit(&format!("    state._nr_pr = {}", active_count));
        self.emit("    state._nr_qs = 0");
        for line in &lines {
            self.emit(line);
        }

        self.indent -= 1;
        self.emit("    return state");
        self.emit("end");
        self.emit("");
    }

    fn emit_proctypes(&mut self, model: &PromelaModel) {
        for decl in &model.declarations {
            match decl {
                TopLevel::Proctype(p) => {
                    self.emit_proctype(p);
                }
                TopLevel::NeverClaim(n) => {
                    self.emit("-- never claim");
                    self.emit("function _spin_transitions_never(state)");
                    self.indent += 1;
                    self.emit(&format!("    -- {} states in never claim", n.body.len()));
                    self.emit("    return {}");
                    self.indent -= 1;
                    self.emit("end");
                    self.emit("");
                }
                TopLevel::Ltl(l) => {
                    self.emit(&format!(
                        "-- LTL: {} = {}",
                        l.name.as_deref().unwrap_or("(unnamed)"),
                        l.formula
                    ));
                }
                TopLevel::CCode(code, _) => {
                    self.emit("-- embedded c_code (executed as Lua)");
                    self.emit("_spin_c_code([===[");
                    self.emit(code);
                    self.emit("]===])");
                }
                _ => {}
            }
        }
    }

    fn emit_proctype(&mut self, p: &ProctypeDef) {
        let fn_name = format!("_spin_transitions_{}", p.name);
        self.proctype_names.push(fn_name.clone());

        self.emit(&format!("-- Proctype: {} (active: {})", p.name, p.active));
        self.emit(&format!("function {}(state)", fn_name));
        self.indent += 1;
        self.emit("    local transitions = {}");
        self.emit("");

        // Emit transition table based on control flow
        self.emit_stmts(&p.body, 0);

        self.emit("    return transitions");
        self.indent -= 1;
        self.emit("end");
        self.emit("");
    }

    fn emit_assignment(&mut self, target: &str, value: &Expression, depth: usize) {
        let expr_str = self.expr_to_lua(value);
        self.emit(&format!("    -- T{}: {}", depth, target));
        self.emit("    table.insert(transitions, {");
        self.indent += 1;
        self.emit("    guard = function() return true end,");
        self.emit(&format!(
            "    effect = function(s) s.{} = {} end",
            target, expr_str
        ));
        self.indent -= 1;
        self.emit("    })");
    }

    fn emit_assert_stmt(&mut self, expr: &Expression) {
        let e = self.expr_to_lua(expr);
        self.emit(&format!("    -- assert({})", e));
        self.emit("    table.insert(transitions, {");
        self.indent += 1;
        self.emit(&format!("    guard = function(s) return {} end,", e));
        self.emit("    effect = function(s) assert({}, 'assertion failed') end");
        self.indent -= 1;
        self.emit("    })");
    }

    fn emit_send_stmt(&mut self, channel: &str, target: &SendTarget, args: &[Expression]) {
        let args_str: Vec<String> = args.iter().map(|a| self.expr_to_lua(a)).collect();
        let args_concat = args_str.join(", ");
        match target {
            SendTarget::Ident(id) => {
                self.emit("    table.insert(transitions, {");
                self.indent += 1;
                self.emit(&format!(
                    "    guard = function(s) return not chan_full(s.{}) end,",
                    channel
                ));
                let args = if args_concat.is_empty() {
                    id.clone()
                } else {
                    format!("{}, {}", id, args_concat)
                };
                self.emit(&format!(
                    "    effect = function(s) chan_send(s.{}, {}) end",
                    channel, args
                ));
                self.indent -= 1;
                self.emit("    })");
            }
            SendTarget::Value(_val) => {
                self.emit("    table.insert(transitions, {");
                self.indent += 1;
                self.emit(&format!(
                    "    guard = function(s) return not chan_full(s.{}) end,",
                    channel
                ));
                self.emit(&format!(
                    "    effect = function(s) chan_send(s.{}, {}) end",
                    channel, args_concat
                ));
                self.indent -= 1;
                self.emit("    })");
            }
        }
    }

    fn emit_recv_stmt(&mut self, channel: &str, target: &RecvTarget) {
        match target {
            RecvTarget::VarList(vars) => {
                let vars_str = vars.join(", ");
                self.emit("    table.insert(transitions, {");
                self.indent += 1;
                self.emit(&format!(
                    "    guard = function(s) return not chan_empty(s.{}) end",
                    channel
                ));
                self.emit(&format!(
                    "    effect = function(s) chan_recv(s.{}, {}) end",
                    channel, vars_str
                ));
                self.indent -= 1;
                self.emit("    })");
            }
            RecvTarget::Eval(_) => {
                self.emit("    -- recv eval (TODO)");
            }
            RecvTarget::Poll(_) => {
                self.emit("    -- recv poll (TODO)");
            }
        }
    }

    fn emit_stmts(&mut self, stmts: &[Stmt], depth: usize) {
        for stmt in stmts {
            match stmt {
                Stmt::Assignment { target, value, .. } => {
                    self.emit_assignment(target, value, depth);
                }
                Stmt::If(guards) => {
                    self.emit_guards("if", guards, depth);
                }
                Stmt::Do(guards) => {
                    self.emit_guards("do", guards, depth);
                }
                Stmt::Goto(label, _) => {
                    self.emit(&format!("    -- goto {}", label));
                    self.emit("    -- TODO: handle goto in codegen");
                }
                Stmt::Break(_) => {
                    self.emit("    -- break (loop exit)");
                }
                Stmt::Assert(expr, _) => {
                    self.emit_assert_stmt(expr);
                }
                Stmt::Printf(fmt, args, _) => {
                    let args_str: Vec<String> = args.iter().map(|a| self.expr_to_lua(a)).collect();
                    let args_concat = args_str.join(", ");
                    self.emit(&format!("    printf('{}', {})", fmt, args_concat));
                }
                Stmt::Send {
                    channel,
                    target,
                    args,
                    ..
                } => {
                    self.emit_send_stmt(channel, target, args);
                }
                Stmt::Recv {
                    channel, target, ..
                } => {
                    self.emit_recv_stmt(channel, target);
                }
                Stmt::Run(name, args, _) => {
                    let args_str: Vec<String> = args.iter().map(|a| self.expr_to_lua(a)).collect();
                    let args_concat = args_str.join(", ");
                    self.emit(&format!("    run({}, {})", name, args_concat));
                }
                Stmt::Unless { .. } => {
                    self.emit("    -- unless (TODO)");
                }
                Stmt::Skip(_) => {
                    self.emit("    -- skip");
                }
                Stmt::Atomic(body, _) | Stmt::DStep(body, _) => {
                    self.emit("    -- atomic/d_step block");
                    // Generate combined guard: all inner stmts executable
                    let guards: Vec<String> = body.iter().map(|s| self.guard_for_stmt(s)).collect();
                    let combined_guard = if guards.iter().all(|g| g == "true") {
                        "true".to_string()
                    } else {
                        let non_trivial: Vec<&str> = guards
                            .iter()
                            .filter_map(|g| if *g != "true" { Some(g.as_str()) } else { None })
                            .collect();
                        if non_trivial.is_empty() {
                            "true".to_string()
                        } else {
                            non_trivial.join(" and ")
                        }
                    };
                    // Generate combined effect: all inner effects in sequence
                    self.emit(&format!("    if {} then", combined_guard));
                    self.indent += 1;
                    self.emit("    table.insert(transitions, {");
                    self.indent += 1;
                    self.emit(&format!(
                        "    guard = function() return {} end,",
                        combined_guard
                    ));
                    self.emit("    effect = function(s)");
                    self.indent += 1;
                    for s in body {
                        self.emit_effect_for_stmt(s);
                    }
                    self.indent -= 1;
                    self.emit("    end");
                    self.indent -= 1;
                    self.emit("    })");
                    self.indent -= 1;
                    self.emit("    end");
                }
                Stmt::Expr(e, _) => {
                    let _ = e; // suppress unused
                    self.emit("    -- expression statement");
                }
                Stmt::VarDecl(_) | Stmt::Label(_, _) => {
                    self.emit("    -- decl/label");
                }
            }
        }
    }

    /// Extract guard expression for a statement (for combined guards in d_step/atomic)
    fn guard_for_stmt(&self, stmt: &Stmt) -> String {
        match stmt {
            Stmt::Send { channel, .. } => format!("not chan_full(s.{})", channel),
            Stmt::Recv { channel, .. } => format!("not chan_empty(s.{})", channel),
            Stmt::Assert(expr, _) => self.expr_to_lua(expr),
            Stmt::Skip(_) | Stmt::Break(_) => "true".to_string(),
            Stmt::Goto(_, _) => "true".to_string(),
            Stmt::Assignment { .. } | Stmt::Expr(_, _) => "true".to_string(),
            Stmt::Printf(_, _, _) => "true".to_string(),
            Stmt::Run(_, _, _) => "true".to_string(),
            Stmt::Atomic(body, _) | Stmt::DStep(body, _) => {
                if body.is_empty() {
                    "true".to_string()
                } else {
                    let gs: Vec<String> = body.iter().map(|s| self.guard_for_stmt(s)).collect();
                    gs.join(" and ")
                }
            }
            Stmt::Unless { .. } => "true".to_string(),
            Stmt::VarDecl(_) | Stmt::Label(_, _) => "true".to_string(),
            Stmt::If(guards) => {
                if guards.is_empty() {
                    "true".to_string()
                } else {
                    let gs: Vec<String> = guards
                        .iter()
                        .map(|g| match &g.condition {
                            Some(e) => self.expr_to_lua(e),
                            None => "true".to_string(),
                        })
                        .collect();
                    gs.join(" or ")
                }
            }
            Stmt::Do(guards) => {
                if guards.is_empty() {
                    "false".to_string()
                } else {
                    let gs: Vec<String> = guards
                        .iter()
                        .map(|g| match &g.condition {
                            Some(e) => self.expr_to_lua(e),
                            None => "true".to_string(),
                        })
                        .collect();
                    gs.join(" or ")
                }
            }
        }
    }

    /// Emit effect-only Lua code for a single statement (no guard, for d_step/atomic)
    fn emit_effect_for_stmt(&mut self, stmt: &Stmt) {
        match stmt {
            Stmt::Assignment { target, value, .. } => {
                let expr_str = self.expr_to_lua(value);
                self.emit(&format!("s.{} = {}", target, expr_str));
            }
            Stmt::Skip(_) | Stmt::Break(_) => {
                self.emit("-- skip/break");
            }
            Stmt::Assert(expr, _) => {
                let e = self.expr_to_lua(expr);
                self.emit(&format!("_spin_assert({}, 'assertion failed')", e));
            }
            Stmt::Goto(_, _) => {
                self.emit("-- goto");
            }
            Stmt::Expr(e, _) => {
                let _ = e;
                self.emit("-- expr");
            }
            Stmt::Printf(fmt, args, _) => {
                let args_str: Vec<String> = args.iter().map(|a| self.expr_to_lua(a)).collect();
                let args_concat = args_str.join(", ");
                self.emit(&format!("_spin_printf('{}', {})", fmt, args_concat));
            }
            Stmt::Run(name, args, _) => {
                let args_str: Vec<String> = args.iter().map(|a| self.expr_to_lua(a)).collect();
                let args_concat = args_str.join(", ");
                self.emit(&format!("run({}, {})", name, args_concat));
            }
            Stmt::Send {
                channel,
                target: _,
                args,
                ..
            } => {
                let args_str: Vec<String> = args.iter().map(|a| self.expr_to_lua(a)).collect();
                let args_concat = args_str.join(", ");
                self.emit(&format!("_spin_chan_send('{}', {})", channel, args_concat));
            }
            Stmt::Recv {
                channel, target, ..
            } => match target {
                RecvTarget::VarList(vars) => {
                    let val = format!("_spin_chan_recv('{}')", channel);
                    if let Some(first_var) = vars.first() {
                        self.emit(&format!("s.{} = {}", first_var, val));
                    }
                }
                _ => {
                    self.emit(&format!("_spin_chan_recv('{}')", channel));
                }
            },
            Stmt::Atomic(body, _) | Stmt::DStep(body, _) => {
                for s in body {
                    self.emit_effect_for_stmt(s);
                }
            }
            Stmt::Unless {
                body, handler: _, ..
            } => {
                for s in body {
                    self.emit_effect_for_stmt(s);
                }
            }
            Stmt::VarDecl(_) | Stmt::Label(_, _) => {
                self.emit("-- decl/label in d_step");
            }
            Stmt::If(guards) => {
                // Use the first enabled guard's body
                for guard in guards {
                    let cond_str = match &guard.condition {
                        Some(e) => self.expr_to_lua(e),
                        None => "true".to_string(),
                    };
                    self.emit(&format!("if {} then", cond_str));
                    self.indent += 1;
                    for s in &guard.body {
                        self.emit_effect_for_stmt(s);
                    }
                    self.indent -= 1;
                    self.emit("end");
                    break;
                }
            }
            Stmt::Do(guards) => {
                // Use the first enabled guard's body
                for guard in guards {
                    let cond_str = match &guard.condition {
                        Some(e) => self.expr_to_lua(e),
                        None => "true".to_string(),
                    };
                    self.emit(&format!("if {} then", cond_str));
                    self.indent += 1;
                    for s in &guard.body {
                        self.emit_effect_for_stmt(s);
                    }
                    self.indent -= 1;
                    self.emit("end");
                    break;
                }
            }
        }
    }

    fn emit_guards(&mut self, kind: &str, guards: &[Guard], _depth: usize) {
        for (i, guard) in guards.iter().enumerate() {
            let cond_str = match &guard.condition {
                Some(e) => self.expr_to_lua(e),
                None => "true".to_string(),
            };

            self.emit(&format!("    -- {} guard {}: {}", kind, i, cond_str));
            self.emit("    table.insert(transitions, {");
            self.indent += 1;
            self.emit(&format!("    guard = function(s) return {} end,", cond_str));
            self.emit("    effect = function(s)");
            self.indent += 1;
            for s in &guard.body {
                // Recursive call for body statements
                match s {
                    Stmt::Assignment { target, value, .. } => {
                        let v = self.expr_to_lua(value);
                        self.emit(&format!("    s.{} = {}", target, v));
                    }
                    Stmt::Break(_) => {
                        self.emit("    -- break");
                    }
                    Stmt::Goto(label, _) => {
                        self.emit(&format!("    -- goto {}", label));
                    }
                    Stmt::Assert(expr, _) => {
                        let e = self.expr_to_lua(expr);
                        self.emit(&format!("    assert({}, 'assertion failed')", e));
                    }
                    Stmt::Send {
                        channel, target, ..
                    } => {
                        let id = match target {
                            SendTarget::Ident(id) => id.clone(),
                            SendTarget::Value(_) => "expr".to_string(),
                        };
                        self.emit(&format!("    chan_send(s.{}, {}, ...)", channel, id));
                    }
                    Stmt::Recv {
                        channel, target, ..
                    } => {
                        if let RecvTarget::VarList(vars) = target {
                            let vs = vars.join(", ");
                            self.emit(&format!("    {}, _ = chan_recv(s.{})", vs, channel));
                        }
                    }
                    Stmt::Skip(_) => {}
                    Stmt::Expr(e, _) => {
                        self.emit(&format!("    -- {}", self.expr_to_lua(e)));
                    }
                    _ => {
                        self.emit("    -- (stmt not yet inlined in codegen)");
                    }
                }
            }
            self.indent -= 1;
            self.emit("    end,");
            // Add depth information
            self.emit(&format!("    label = \"{}:guard{}\",", kind, i));
            self.indent -= 1;
            self.emit("    })");
        }
    }

    fn emit_trailer(&mut self) {
        self.emit("-- Main transition dispatcher");
        self.emit("-- Called by Rust engine to enumerate transitions");
        self.emit("function _spin_get_transitions(state)");
        self.indent += 1;
        self.emit("    local all = {}");
        let names = self.proctype_names.clone();
        for name in names {
            self.emit(&format!("    local t = {}(state)", name));
            self.emit("    for _, tr in ipairs(t) do");
            self.emit("        table.insert(all, tr)");
            self.emit("    end");
        }
        self.emit("    return all");
        self.indent -= 1;
        self.emit("end");
        self.emit("");

        self.emit("-- State hashing callback");
        self.emit("function _spin_hash(state)");
        self.indent += 1;
        self.emit("    return state_hash(state)");
        self.indent -= 1;
        self.emit("end");
    }

    fn expr_to_lua(&self, expr: &Expression) -> String {
        self.special_expr_to_lua(expr)
    }

    fn unary_to_lua(&self, op: &UnaryOp, e: &Expression) -> String {
        use UnaryOp::*;
        let table: &[(UnaryOp, &str)] = &[
            (Not, "not "),
            (BitNot, "~"),
            (Neg, "-"),
            (Always, "[]"),
            (Eventually, "<>"),
            (Next, "X"),
        ];
        let op_str = table
            .iter()
            .find(|(k, _)| k == op)
            .map(|(_, v)| *v)
            .unwrap_or("");
        format!("{}{}", op_str, self.expr_to_lua(e))
    }

    fn binary_op_to_lua(&self, op: &BinaryOp) -> &'static str {
        use BinaryOp::*;
        let table: &[(BinaryOp, &str)] = &[
            (Add, " + "),
            (Sub, " - "),
            (Mul, " * "),
            (Div, " / "),
            (Mod, " % "),
            (Eq, " == "),
            (Neq, " ~= "),
            (Lt, " < "),
            (Le, " <= "),
            (Gt, " > "),
            (Ge, " >= "),
            (And, " and "),
            (Or, " or "),
            (BitAnd, " & "),
            (BitOr, " | "),
            (BitXor, " // "),
            (Shl, " << "),
            (Shr, " >> "),
            (Impl, " -> "),
            (BiImpl, " <-> "),
            (Until, " U "),
            (Release, " V "),
        ];
        table
            .iter()
            .find(|(k, _)| k == op)
            .map(|(_, v)| *v)
            .unwrap_or("")
    }

    fn special_expr_to_lua(&self, expr: &Expression) -> String {
        match expr {
            Expression::IntLit(n) => n.to_string(),
            Expression::StringLit(s) => format!("\"{}\"", s),
            Expression::BoolLit(b) => b.to_string(),
            Expression::Ident(name) => format!("s.{}", name),
            Expression::ArrayAccess { name, index } => {
                format!("s.{}[{}]", name, self.expr_to_lua(index))
            }
            Expression::UnaryOp { op, expr: e } => self.unary_to_lua(op, e),
            Expression::BinaryOp { op, left, right } => format!(
                "{}{}{}",
                self.expr_to_lua(left),
                self.binary_op_to_lua(op),
                self.expr_to_lua(right)
            ),
            Expression::FuncCall { name, args } => {
                let args_str: Vec<String> = args.iter().map(|a| self.expr_to_lua(a)).collect();
                format!("{}({})", name, args_str.join(", "))
            }
            Expression::Len(_) => "0".to_string(),
            Expression::Full(ch) => format!("chan_full(s.{})", ch),
            Expression::Empty(ch) => format!("chan_empty(s.{})", ch),
            Expression::NFull(_) => "false".to_string(),
            Expression::NEmpty(_) => "false".to_string(),
            Expression::Enabled(_) => "true".to_string(),
            Expression::Timeout => "false".to_string(),
            Expression::RemoteRef { pid, name } => {
                let pid_str = self.expr_to_lua(pid);
                format!("_spin_remote_ref({}, '{}')", pid_str, name)
            }
            Expression::RecordAccess { record, field } => {
                format!("{}[\"{}\"]", self.expr_to_lua(record), field)
            }
            Expression::ChannelSend { channel, target } => {
                format!("s.{}[{}]", channel, self.expr_to_lua(target))
            }
            Expression::ChannelPoll { channel, .. } => format!("not chan_empty(s.{})", channel),
        }
    }

    fn finish(self) -> GeneratedLua {
        GeneratedLua {
            source: self.source,
            proctype_fn_names: self.proctype_names,
        }
    }
}

fn default_value(var_type: &VarType) -> String {
    match var_type {
        VarType::Bit | VarType::Bool | VarType::Byte => "0".to_string(),
        VarType::Short | VarType::Int | VarType::Unsigned(_) => "0".to_string(),
        VarType::Chan => "nil".to_string(),
        VarType::Mtype => "0".to_string(),
        VarType::Named(_) => "nil".to_string(),
    }
}

